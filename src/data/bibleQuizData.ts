// Algorithmic generator for dynamic new questions across Bible books
export function generateDynamicBookQuestion(bookId: string, bookNameFr: string, bookNameKr: string, chaptersCount: number, testament: 'AT' | 'NT'): QuizQuestion {
  const types = ['chapter_count', 'testament_type', 'spiritual_theme'];
  const chosenType = types[Math.floor(Math.random() * types.length)];

  if (chosenType === 'chapter_count') {
    const correct = chaptersCount;
    const offsets = [-3, -1, 2, 5, 8].filter(o => correct + o > 0);
    const shuffledOffsets = offsets.sort(() => 0.5 - Math.random()).slice(0, 3);
    const optionsNumbers = [correct, ...shuffledOffsets.map(o => correct + o)].sort(() => 0.5 - Math.random());
    const correctIdx = optionsNumbers.indexOf(correct);

    return {
      id: `dyn-ch-${bookId}-${Date.now()}-${Math.random()}`,
      category: testament === 'AT' ? 'pentateuque' : 'evangiles',
      difficulty: 'medium',
      bookId,
      bookNameFr,
      bookNameKr,
      referenceFr: `${bookNameFr} (Vue générale)`,
      referenceKr: `${bookNameKr} (Apèsi jeneral)`,
      questionFr: `Combien de chapitres contient le livre biblique de « ${bookNameFr} » ?`,
      questionKr: `Konbyen chapit ki genyen nan liv biblik « ${bookNameKr} » ?`,
      optionsFr: optionsNumbers.map(n => `${n} chapitres`),
      optionsKr: optionsNumbers.map(n => `${n} chapit`),
      correctIndex: correctIdx,
      explanationFr: `Le livre de ${bookNameFr} comprend exactement ${chaptersCount} chapitres dans le canon biblique.`,
      explanationKr: `Liv ${bookNameKr} a genyen egzakteman ${chaptersCount} chapit nan Labib la.`,
    };
  }

  if (chosenType === 'testament_type') {
    const isAT = testament === 'AT';
    return {
      id: `dyn-test-${bookId}-${Date.now()}-${Math.random()}`,
      category: isAT ? 'histoire' : 'actes_epitres',
      difficulty: 'easy',
      bookId,
      bookNameFr,
      bookNameKr,
      referenceFr: `${bookNameFr} (Canon biblique)`,
      referenceKr: `${bookNameKr} (Kanon biblik)`,
      questionFr: `Dans quelle partie de la Sainte Bible se trouve le livre de « ${bookNameFr} » ?`,
      questionKr: `Nan ki pati nan Bib la nou jwenn liv « ${bookNameKr} » ?`,
      optionsFr: [
        isAT ? 'Ancien Testament' : 'Nouveau Testament',
        isAT ? 'Nouveau Testament' : 'Ancien Testament',
        'Livres apocryphes seulement',
        'Dans aucun des deux testaments',
      ],
      optionsKr: [
        isAT ? 'Ansyen Testaman' : 'Nouvo Testaman',
        isAT ? 'Nouvo Testaman' : 'Ansyen Testaman',
        'Liv apokrif sèlman',
        'Nan okenn nan de testaman yo',
      ],
      correctIndex: 0,
      explanationFr: `Le livre de ${bookNameFr} fait partie intégrante de l'${isAT ? 'Ancien' : 'Nouveau'} Testament.`,
      explanationKr: `Liv ${bookNameKr} a fè pati ${isAT ? 'Ansyen' : 'Nouvo'} Testaman an.`,
    };
  }

  // General theme question
  return {
    id: `dyn-thm-${bookId}-${Date.now()}-${Math.random()}`,
    category: testament === 'AT' ? 'prophetes' : 'evangiles',
    difficulty: 'easy',
    bookId,
    bookNameFr,
    bookNameKr,
    referenceFr: `${bookNameFr}`,
    referenceKr: `${bookNameKr}`,
    questionFr: `Quel est le but suprême de la méditation du livre de « ${bookNameFr} » ?`,
    questionKr: `Ki prensipal objektif lè yon moun ap medite liv « ${bookNameKr} » ?`,
    optionsFr: [
      'Connaître Dieu, grandir dans la foi en Christ et mettre sa Parole en pratique',
      'Acquérir des richesses matérielles rapides sans travailler',
      'Gagner des débats religieux contre ses voisins',
      'Prédire l\'avenir comme un astrologue',
    ],
    optionsKr: [
      'Konnen Bondye pi byen, grandi nan lafwa nan Kris la epi viv Pawòl la chak jou',
      'Fè lajan vit san travay',
      'Genyen diskisyon relijye ak vwazen nou',
      'Chache konnen lavni tankou moun k\'ap gade zetwal',
    ],
    correctIndex: 0,
    explanationFr: `Toute l'Écriture dans ${bookNameFr} est divinement inspirée pour enseigner, convaincre, corriger et instruire dans la justice (2 Timothée 3:16).`,
    explanationKr: `Tout sa ki ekri nan ${bookNameKr} enspire pa Bondye pou moutre verite a, pou korije nou e pou fòme nou nan jan Bondye vle n viv la (2 Timote 3:16).`,
  };
}
